#!/usr/bin/env node
/**
 * F01 member/content migration: the existing service's database → this backend's schema.
 *
 *   node --no-warnings tools/migrate-members.mjs --source <export.sql | db.sqlite> --work <dir> [--verify]
 *
 * --source  `wrangler d1 export` SQL or an SQLite file of the existing service. Read only.
 * --work    output folder:
 *             import.sql    INSERT OR IGNORE statements (safe to apply twice), ids kept as they are
 *             report.json   per entity: source rows, imported, skipped by reason; value mappings;
 *                           every source table with its row count and whether it was carried over
 *             samples.json  20 deterministic sample ids per entity, source vs new values side by side
 * --verify  builds an empty database from ../migrations, applies import.sql TWICE, then checks:
 *           foreign keys, row counts = report, the samples, and that the second run changed nothing.
 *
 * Ids stay the same (members.id = users.id, shops.id = stores.id = room id …), so old links and
 * sample-id comparisons work. Nothing is deleted: rows the old service hid are imported hidden
 * (deleted_at) where this schema can, and everything not carried over is listed in the report.
 *
 * Applying to a real database is a separate, deliberate step on the client's Cloudflare account:
 *   npx wrangler d1 execute <their new db> --remote --file <work>/media-import.sql   (photos first)
 *   npx wrangler d1 execute <their new db> --remote --file <work>/import.sql
 */
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';

const args = process.argv.slice(2);
const opt = n => {
  const i = args.indexOf('--' + n);
  return i < 0 ? undefined : args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : true;
};
const source = opt('source');
const work = opt('work');
if (typeof source !== 'string' || typeof work !== 'string') {
  console.error('usage: migrate-members.mjs --source <export.sql|db.sqlite> --work <dir> [--verify]');
  process.exit(2);
}
const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));

// ── Value mappings (all reported, so Peter/the operator can check them) ─────
/** 업종: the existing service's labels → our three groups. Its own UI groups 텐 and 일프로 together. */
const INDUSTRY = { 하이퍼블릭: 'hyperpublic', 쩜오: 'jjeomo', 텐: 'ten', 텐카페: 'ten', 텐프로: 'ten', 일프로: 'ten' };
/** First word of shops.area ("강남 역삼") → region code; the rest becomes the 동네. */
const REGION = { 강남: 'gangnam', 홍대: 'hongdae', 잠실: 'jamsil' };
const ROOM_MEMBER_STATE = { joined: 'active', pending: 'pending', left: 'left', banned: 'blocked' };

// ── Source ─────────────────────────────────────────────────────────────────
let src;
if (/\.sql$/i.test(source)) {
  src = new DatabaseSync(':memory:');
  src.exec(fs.readFileSync(source, 'utf8'));
} else src = new DatabaseSync(source, { readOnly: true });
const has = t => !!src.prepare("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?").get(t);
const rows = (t, sql) => (has(t) ? src.prepare(sql).all() : []);

const ms = iso => {
  const v = Date.parse(iso);
  return Number.isFinite(v) ? v : null;
};
const lit = v => (v == null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const ins = (table, cols, vals) => `INSERT OR IGNORE INTO ${table} (${cols.join(', ')}) VALUES (${vals.map(lit).join(', ')});`;

const sql = ['-- Generated by tools/migrate-members.mjs. Safe to apply more than once (INSERT OR IGNORE).', 'PRAGMA defer_foreign_keys = ON;'];
const entities = {};
const samples = {};
const mappings = { industry: {}, region: {}, postCategory: {}, unmappedRegions: {} };
const E = name => (entities[name] ??= { source: 0, imported: 0, skipped: {} });
const skip = (e, reason) => (e.skipped[reason] = (e.skipped[reason] ?? 0) + 1);
const carried = new Set();

// ── Members → users (+ nickname, withdrawn) ────────────────────────────────
const users = new Set();
{
  const e = E('users');
  const nick = new Map(rows('community_profiles', 'SELECT user_id, nickname FROM community_profiles').map(r => [r.user_id, r.nickname]));
  const closed = new Set(rows('account_closures', 'SELECT user_id FROM account_closures').map(r => r.user_id));
  e.nicknameFallback = 0;
  for (const m of rows('members', 'SELECT id, created_at FROM members ORDER BY id')) {
    e.source++;
    const created = ms(m.created_at);
    if (created == null) { skip(e, 'bad_created_at'); continue; }
    let nickname = nick.get(m.id)?.trim();
    if (!nickname) { nickname = '회원' + createHash('sha256').update(m.id).digest('hex').slice(0, 4); e.nicknameFallback++; }
    sql.push(ins('users', ['id', 'nickname', 'role', 'status', 'created_at'], [m.id, nickname, 'member', closed.has(m.id) ? 'withdrawn' : 'active', created]));
    users.add(m.id);
    e.imported++;
  }
  e.withdrawn = [...users].filter(u => closed.has(u)).length;
  ['members', 'community_profiles', 'account_closures'].forEach(t => carried.add(t));
}

// ── Google/Naver identities ────────────────────────────────────────────────
{
  const e = E('oauth_links');
  for (const r of rows('member_oauth_links', 'SELECT provider, subject_hash, user_id, created_at FROM member_oauth_links ORDER BY provider, subject_hash')) {
    e.source++;
    if (!users.has(r.user_id)) { skip(e, 'member_missing'); continue; }
    sql.push(ins('oauth_links', ['provider', 'subject_hash', 'user_id', 'created_at'], [r.provider, r.subject_hash, r.user_id, ms(r.created_at) ?? 0]));
    e.imported++;
  }
  carried.add('member_oauth_links');
}

// ── Shops → stores (+ one store room per listed shop) ──────────────────────
const shopRooms = new Set();
{
  const e = E('stores');
  const r2 = E('store_rooms');
  e.unlistedKeptHidden = 0;
  for (const s of rows('shops', 'SELECT id, name, area, industry, created_at, listed FROM shops ORDER BY id')) {
    e.source++;
    const created = ms(s.created_at);
    if (created == null) { skip(e, 'bad_created_at'); continue; }
    const [first, ...rest] = String(s.area ?? '').trim().split(/\s+/);
    const region = REGION[first] ?? 'etc';
    if (!REGION[first]) mappings.unmappedRegions[s.area] = (mappings.unmappedRegions[s.area] ?? 0) + 1;
    mappings.region[`${first} → ${region}`] = (mappings.region[`${first} → ${region}`] ?? 0) + 1;
    const category = INDUSTRY[s.industry] ?? null;
    mappings.industry[`${s.industry} → ${category ?? '(none)'}`] = (mappings.industry[`${s.industry} → ${category ?? '(none)'}`] ?? 0) + 1;
    sql.push(ins('stores', ['id', 'name', 'region', 'area', 'category', 'source_industry', 'created_at'], [s.id, s.name, region, rest.join(' ') || null, category, s.industry, created]));
    e.imported++;
    // Unlisted shops are kept but get no room, so they stay out of the 초이스톡 list (hidden, not deleted).
    if (s.listed === 0) { e.unlistedKeptHidden++; continue; }
    r2.source++;
    sql.push(ins('rooms', ['id', 'kind', 'title', 'region', 'status', 'join_policy', 'store_id', 'created_at'], [s.id, 'store', s.name, region, 'open', 'open', s.id, created]));
    shopRooms.add(s.id);
    r2.imported++;
  }
  // Cover photo from the photo migration (tools/migrate-photos.mjs, applied first): shop_photos.image.
  sql.push(`UPDATE stores SET cover_media_id = (SELECT r.media_id FROM legacy_media_refs r WHERE r.source_table = 'shop_photos' AND r.source_column = 'image' AND r.source_pk = json_object('shop_id', stores.id)) WHERE cover_media_id IS NULL AND source_industry IS NOT NULL;`);
  ['shops', 'shop_photos'].forEach(t => carried.add(t));
}

// ── Latest live status per shop ────────────────────────────────────────────
{
  const e = E('room_status');
  e.approximateChoiceLeftEmpty = 0;
  const latest = new Map(); // shop → { choice, entry, waiting, vacancy, at, by }
  for (const r of rows('status_reports', "SELECT shop_id, author_id, state, note, created_at FROM status_reports WHERE kind = 'status' ORDER BY created_at, id")) {
    const at = ms(r.created_at);
    if (at == null || !shopRooms.has(r.shop_id) || !users.has(r.author_id)) continue;
    const cur = latest.get(r.shop_id) ?? { choice: null, entry: null, waiting: null, vacancy: null, at: 0, by: null, reports: 0 };
    cur.reports++;
    const text = `${r.state} ${r.note}`;
    const exactChoice = /^초중\s*(\d+)\s*$/.exec(r.state.trim());
    if (exactChoice) cur.choice = +exactChoice[1];
    else if (/^초중/.test(r.state.trim())) { cur.choice = null; e.approximateChoiceLeftEmpty++; } // "20 미만" is not a number; don't guess
    const num = word => { const m = new RegExp(word + '\\s*(\\d+)').exec(text); return m ? +m[1] : undefined; };
    for (const [k, w] of [['entry', '엔트리'], ['waiting', '대기'], ['vacancy', '빈방']]) { const v = num(w); if (v !== undefined) cur[k] = v; }
    cur.at = at;
    cur.by = r.author_id;
    latest.set(r.shop_id, cur);
  }
  e.source = rows('status_reports', 'SELECT COUNT(*) AS n FROM status_reports')[0]?.n ?? 0;
  for (const [shop, s] of latest) {
    sql.push(ins('room_status', ['room_id', 'choice', 'entry', 'waiting', 'vacancy', 'updated_at', 'updated_by'], [shop, s.choice, s.entry, s.waiting, s.vacancy, s.at, s.by]));
    e.imported++;
  }
  e.note = 'one row per shop = its latest reports; older reports stay in the old database';
  carried.add('status_reports');
}

// ── Saved shops ────────────────────────────────────────────────────────────
{
  const e = E('saved_rooms');
  for (const r of rows('saved_shops', 'SELECT user_id, shop_id, created_at FROM saved_shops ORDER BY id')) {
    e.source++;
    if (!users.has(r.user_id)) { skip(e, 'member_missing'); continue; }
    if (!shopRooms.has(r.shop_id)) { skip(e, 'shop_missing_or_unlisted'); continue; }
    sql.push(ins('saved_items', ['user_id', 'target_type', 'target_id', 'created_at'], [r.user_id, 'room', r.shop_id, ms(r.created_at) ?? 0]));
    e.imported++;
  }
  carried.add('saved_shops');
}

// ── Board: posts, comments, likes ──────────────────────────────────────────
const posts = new Set();
{
  const e = E('posts');
  e.hiddenKept = 0;
  for (const p of rows('community_posts', 'SELECT id, author, category, title, body, state, created_at, updated_at FROM community_posts ORDER BY id')) {
    e.source++;
    if (!users.has(p.author)) { skip(e, 'author_missing'); continue; }
    const created = ms(p.created_at);
    if (created == null) { skip(e, 'bad_created_at'); continue; }
    const hidden = p.state !== 'published';
    if (hidden) e.hiddenKept++;
    mappings.postCategory[p.category] = (mappings.postCategory[p.category] ?? 0) + 1;
    sql.push(ins('posts', ['id', 'author_id', 'board', 'category', 'title', 'body', 'mutation_id', 'created_at', 'deleted_at'],
      [p.id, p.author, 'lounge', p.category, p.title, p.body, 'legacy:' + p.id, created, hidden ? ms(p.updated_at) ?? created : null]));
    posts.add(p.id);
    e.imported++;
  }
  const c = E('comments');
  c.hiddenKept = 0;
  for (const r of rows('community_comments', 'SELECT id, post_id, author, body, state, created_at FROM community_comments ORDER BY id')) {
    c.source++;
    if (!posts.has(r.post_id)) { skip(c, 'post_missing'); continue; }
    if (!users.has(r.author)) { skip(c, 'author_missing'); continue; }
    const created = ms(r.created_at);
    if (created == null) { skip(c, 'bad_created_at'); continue; }
    const hidden = r.state !== 'published';
    if (hidden) c.hiddenKept++;
    sql.push(ins('comments', ['id', 'post_id', 'author_id', 'body', 'mutation_id', 'created_at', 'deleted_at'], [r.id, r.post_id, r.author, r.body, 'legacy:' + r.id, created, hidden ? created : null]));
    c.imported++;
  }
  const l = E('post_likes');
  const seen = new Set();
  for (const r of rows('community_likes', 'SELECT id, post_id, author FROM community_likes ORDER BY id')) {
    l.source++;
    if (!posts.has(r.post_id)) { skip(l, 'post_missing'); continue; }
    if (!users.has(r.author)) { skip(l, 'member_missing'); continue; }
    const k = r.post_id + '|' + r.author;
    if (seen.has(k)) { skip(l, 'duplicate_like'); continue; }
    seen.add(k);
    sql.push(ins('post_likes', ['post_id', 'user_id', 'created_at'], [r.post_id, r.author, 0]));
    l.imported++;
  }
  sql.push("UPDATE posts SET like_count = (SELECT COUNT(*) FROM post_likes WHERE post_id = posts.id), comment_count = (SELECT COUNT(*) FROM comments WHERE post_id = posts.id AND deleted_at IS NULL) WHERE mutation_id LIKE 'legacy:%';");
  ['community_posts', 'community_comments', 'community_likes'].forEach(t => carried.add(t));
}

// ── Chat rooms (오픈톡 with per-room aliases → 익명 오픈톡), members, messages ──
const chatRooms = new Set();
{
  const e = E('chat_rooms');
  for (const r of rows('social_rooms', 'SELECT id, owner, kind, title, area, capacity, approval, state, created_at FROM social_rooms ORDER BY id')) {
    e.source++;
    if (shopRooms.has(r.id)) { skip(e, 'id_collides_with_shop'); continue; }
    const created = ms(r.created_at);
    if (created == null) { skip(e, 'bad_created_at'); continue; }
    const region = REGION[String(r.area ?? '').trim().split(/\s+/)[0]] ?? null;
    sql.push(ins('rooms', ['id', 'kind', 'title', 'region', 'status', 'join_policy', 'capacity', 'anonymous', 'created_at'],
      [r.id, 'general', r.title, region, r.state === 'open' ? 'open' : 'closed', r.approval ? 'approval' : 'open', r.capacity, 1, created]));
    chatRooms.add(r.id);
    e.imported++;
    if (users.has(r.owner)) sql.push(ins('room_members', ['room_id', 'user_id', 'state', 'role', 'updated_at'], [r.id, r.owner, 'active', 'manager', created]));
  }
  const m = E('chat_room_members');
  for (const r of rows('social_room_members', 'SELECT room_id, user_id, state, joined_at FROM social_room_members ORDER BY room_id, user_id')) {
    m.source++;
    if (!chatRooms.has(r.room_id)) { skip(m, 'room_missing'); continue; }
    if (!users.has(r.user_id)) { skip(m, 'member_missing'); continue; }
    const state = ROOM_MEMBER_STATE[r.state];
    if (!state) { skip(m, 'unknown_state'); continue; }
    sql.push(ins('room_members', ['room_id', 'user_id', 'state', 'role', 'updated_at'], [r.room_id, r.user_id, state, 'member', ms(r.joined_at) ?? 0]));
    m.imported++;
  }
  const g = E('chat_messages');
  for (const r of rows('social_messages', 'SELECT seq, id, room_id, author, body, state, created_at FROM social_messages ORDER BY seq')) {
    g.source++;
    if (!chatRooms.has(r.room_id)) { skip(g, 'room_missing'); continue; }
    if (!users.has(r.author)) { skip(g, 'member_missing'); continue; }
    if (r.state !== 'published') { skip(g, 'hidden_in_old_service_left_there'); continue; }
    sql.push(ins('room_messages', ['id', 'room_id', 'sender_id', 'body', 'request_id', 'created_at'], [r.id, r.room_id, r.author, r.body, 'legacy:' + r.id, ms(r.created_at) ?? 0]));
    g.imported++;
  }
  ['social_rooms', 'social_room_members', 'social_messages'].forEach(t => carried.add(t));
}

// ── Report ─────────────────────────────────────────────────────────────────
const allTables = src.prepare("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' AND name NOT LIKE '_cf_%' ORDER BY name").all().map(r => r.name);
const tables = allTables.map(t => ({ table: t, rows: src.prepare(`SELECT COUNT(*) AS n FROM "${t.replace(/"/g, '""')}"`).get().n, carried: carried.has(t) }));
const notCarriedWithRows = tables.filter(t => !t.carried && t.rows > 0);

// Deterministic samples: the 20 ids with the smallest sha256, per entity.
const pick = list => list.map(id => [createHash('sha256').update(String(id)).digest('hex'), id]).sort().slice(0, 20).map(x => x[1]);
samples.users = pick([...users]).map(id => {
  const m = src.prepare('SELECT id, created_at FROM members WHERE id = ?').get(id);
  return { id, source: { created_at: m.created_at }, expect: { created_at: ms(m.created_at) } };
});
samples.stores = pick(rows('shops', 'SELECT id FROM shops').map(r => r.id)).map(id => {
  const s = src.prepare('SELECT id, name, area, industry FROM shops WHERE id = ?').get(id);
  return { id, source: { name: s.name, area: s.area, industry: s.industry }, expect: { name: s.name, category: INDUSTRY[s.industry] ?? null, source_industry: s.industry } };
});
samples.posts = pick([...posts]).map(id => {
  const p = src.prepare('SELECT id, title, author FROM community_posts WHERE id = ?').get(id);
  return { id, source: { title: p.title, author: p.author }, expect: { title: p.title, author_id: p.author } };
});

fs.mkdirSync(work, { recursive: true });
fs.writeFileSync(path.join(work, 'import.sql'), sql.join('\n') + '\n');
fs.writeFileSync(path.join(work, 'samples.json'), JSON.stringify(samples, null, 2) + '\n');
const report = {
  source: path.basename(source),
  entities,
  mappings,
  sourceTables: { total: tables.length, carriedOver: tables.filter(t => t.carried).map(t => `${t.table} (${t.rows})`), notCarriedWithRows: notCarriedWithRows.map(t => `${t.table} (${t.rows})`) },
};

// ── Verify on an empty copy of this backend's schema ───────────────────────
if (opt('verify')) {
  const db = new DatabaseSync(':memory:');
  db.exec('PRAGMA foreign_keys = ON;');
  for (const f of fs.readdirSync(path.join(here, '..', 'migrations')).filter(f => f.endsWith('.sql')).sort()) db.exec(fs.readFileSync(path.join(here, '..', 'migrations', f), 'utf8'));
  const count = (t, where = '') => db.prepare(`SELECT COUNT(*) AS n FROM ${t} ${where}`).get().n;
  const snapshot = () => ['users', 'oauth_links', 'stores', 'rooms', 'room_status', 'saved_items', 'posts', 'comments', 'post_likes', 'room_members', 'room_messages'].map(t => count(t)).join(',');
  const importSql = fs.readFileSync(path.join(work, 'import.sql'), 'utf8');
  db.exec(importSql);
  const first = snapshot();
  db.exec(importSql);
  const second = snapshot();
  const fk = db.prepare('PRAGMA foreign_key_check').all();
  const expect = {
    users: entities.users.imported, oauth_links: entities.oauth_links.imported, stores: entities.stores.imported,
    rooms: entities.store_rooms.imported + entities.chat_rooms.imported, room_status: entities.room_status.imported,
    saved_items: entities.saved_rooms.imported, posts: entities.posts.imported, comments: entities.comments.imported,
    post_likes: entities.post_likes.imported, room_messages: entities.chat_messages.imported,
  };
  const counts = Object.fromEntries(Object.keys(expect).map(t => [t, count(t)]));
  const countMismatch = Object.keys(expect).filter(t => counts[t] !== expect[t]);
  const sampleMismatch = [];
  for (const s of samples.users) { const r = db.prepare('SELECT created_at FROM users WHERE id = ?').get(s.id); if (!r || r.created_at !== s.expect.created_at) sampleMismatch.push(['users', s.id]); }
  for (const s of samples.stores) { const r = db.prepare('SELECT name, category, source_industry FROM stores WHERE id = ?').get(s.id); if (!r || r.name !== s.expect.name || r.category !== s.expect.category || r.source_industry !== s.expect.source_industry) sampleMismatch.push(['stores', s.id]); }
  for (const s of samples.posts) { const r = db.prepare('SELECT title, author_id FROM posts WHERE id = ?').get(s.id); if (!r || r.title !== s.expect.title || r.author_id !== s.expect.author_id) sampleMismatch.push(['posts', s.id]); }
  report.verify = { counts, countMismatch, foreignKeyProblems: fk.length, sampleMismatch, secondRunChangedNothing: first === second };
}

fs.writeFileSync(path.join(work, 'report.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report, null, 2));
const v = report.verify;
if (v && (v.countMismatch.length || v.foreignKeyProblems || v.sampleMismatch.length || !v.secondRunChangedNothing)) process.exit(1);
